import itertools, sys
from xml.sax.saxutils import quoteattr

C = dict(core=('#e1d5e7', '#9673a6'), contract=('#dae8fc', '#6c8ebf'), ext=('#f5f5f5', '#666666'),
         ok=('#d5e8d4', '#82b366'), part=('#fff2cc', '#d6b656'), miss=('#ffe6cc', '#d79b00'),
         stop=('#f8cecc', '#b85450'), white=('#ffffff', '#666666'))
EDGE = 'edgeStyle=orthogonalEdgeStyle;rounded=0;html=1;endArrow=block;endFill=1;strokeColor=#555555;fontSize=11;labelBackgroundColor=#ffffff;'


class Page:
    def __init__(self, name, w=1169, h=827):
        self.name, self.w, self.h, self.cells, self.n = name, w, h, [], itertools.count(2)

    def _id(self):
        return 'c%d' % next(self.n)

    def v(self, x, y, w, h, label, style):
        i = self._id()
        self.cells.append('<mxCell id="%s" value=%s style="%s" vertex="1" parent="1"><mxGeometry x="%d" y="%d" width="%d" height="%d" as="geometry"/></mxCell>' % (i, quoteattr(label), style, x, y, w, h))
        return i

    def lab(self, title, sub=''):
        return '<b>%s</b>' % title + ('<br><font style="font-size:11px">%s</font>' % sub if sub else '')

    def box(self, x, y, w, h, title, sub='', color='ext', extra=''):
        f, s = C[color]
        return self.v(x, y, w, h, self.lab(title, sub), 'rounded=1;whiteSpace=wrap;html=1;fillColor=%s;strokeColor=%s;arcSize=12;%s' % (f, s, extra))

    def group(self, x, y, w, h, title):
        return self.v(x, y, w, h, '<b>%s</b>' % title, 'rounded=1;whiteSpace=wrap;html=1;dashed=1;fillColor=none;strokeColor=#999999;verticalAlign=top;align=left;spacingLeft=12;spacingTop=6;arcSize=3;')

    def frame(self, x, y, w, h, title):
        return self.v(x, y, w, h, '<b>%s</b>' % title, 'rounded=0;whiteSpace=wrap;html=1;fillColor=none;strokeColor=#666666;verticalAlign=top;align=center;spacingTop=6;')

    def actor(self, x, y, title):
        return self.v(x, y, 40, 80, title, 'shape=umlActor;verticalLabelPosition=bottom;verticalAlign=top;html=1;outlineConnect=0;')

    def ell(self, x, y, w, h, title, sub='', color='ok'):
        f, s = C[color]
        return self.v(x, y, w, h, self.lab(title, sub), 'ellipse;whiteSpace=wrap;html=1;fillColor=%s;strokeColor=%s;' % (f, s))

    def dia(self, x, y, w, h, title):
        return self.v(x, y, w, h, '<b>%s</b>' % title, 'rhombus;whiteSpace=wrap;html=1;fillColor=#fff2cc;strokeColor=#d6b656;')

    def cyl(self, x, y, w, h, title, sub=''):
        return self.v(x, y, w, h, self.lab(title, sub), 'shape=cylinder3;whiteSpace=wrap;html=1;boundedLbl=1;backgroundOutline=1;size=12;fillColor=#e1d5e7;strokeColor=#9673a6;')

    def text(self, x, y, w, h, label, align='left', size=12, bold=False):
        return self.v(x, y, w, h, label, 'text;html=1;align=%s;verticalAlign=middle;whiteSpace=wrap;fontSize=%d;strokeColor=none;fillColor=none;%s' % (align, size, 'fontStyle=1;' if bold else ''))

    def note(self, x, y, w, h, label):
        return self.v(x, y, w, h, label, 'shape=note;whiteSpace=wrap;html=1;backgroundOutline=1;size=14;fillColor=#fff2cc;strokeColor=#d6b656;align=left;spacingLeft=8;spacingRight=8;fontSize=11;')

    def lane(self, x, y, w, h, title):
        return self.v(x, y, w, h, title, 'swimlane;whiteSpace=wrap;html=1;startSize=30;fillColor=#f5f5f5;strokeColor=#999999;fontStyle=1;')

    def e(self, a, b, label='', style='', points=None):
        i = self._id()
        pts = ''
        if points:
            pts = '<Array as="points">%s</Array>' % ''.join('<mxPoint x="%d" y="%d"/>' % p for p in points)
        self.cells.append('<mxCell id="%s" value=%s style="%s" edge="1" parent="1" source="%s" target="%s"><mxGeometry relative="1" as="geometry">%s</mxGeometry></mxCell>' % (i, quoteattr(label), EDGE + style, a, b, pts))
        return i

    def xml(self, idx):
        return ('<diagram id="p%d" name=%s><mxGraphModel dx="1200" dy="800" grid="1" gridSize="10" guides="1" tooltips="1" connect="1" arrows="1" fold="1" page="1" pageScale="1" pageWidth="%d" pageHeight="%d" math="0" shadow="0"><root><mxCell id="0"/><mxCell id="1" parent="0"/>%s</root></mxGraphModel></diagram>'
                % (idx, quoteattr(self.name), self.w, self.h, ''.join(self.cells)))


def legend(p, x, y, items):
    for k, (color, label) in enumerate(items):
        f, s = C[color]
        p.v(x, y + 26 * k, 18, 18, '', 'rounded=1;html=1;fillColor=%s;strokeColor=%s;' % (f, s))
        p.text(x + 26, y + 26 * k - 1, 260, 20, label, size=11)


BI = 'startArrow=block;startFill=1;'
LINE = 'endArrow=none;'


def renumber(pages, prefix):
    for n, p in enumerate(pages, 1):
        old, rest = p.name.split('. ', 1)
        p.name = '%d. %s' % (n, rest)
        p.cells[0] = p.cells[0].replace('%s%s.' % (prefix, old), '%s%d.' % (prefix, n), 1)
    return pages


