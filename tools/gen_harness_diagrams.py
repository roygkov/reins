def chain(p, items, y, x0, w, step, h=70):
    ids = []
    for i, (t, s, col) in enumerate(items):
        ids.append(p.box(x0 + step * i, y, w, h, t, s, col))
        if i:
            p.e(ids[i - 1], ids[i])
    return ids


def code(p, x, y, w, h, src):
    html = '<br>'.join(l.replace(' ', '&nbsp;') for l in src.split('\n'))
    return p.v(x, y, w, h, html, 'rounded=1;whiteSpace=wrap;html=1;fillColor=#f5f5f5;strokeColor=#666666;arcSize=2;align=left;verticalAlign=top;spacingLeft=14;spacingTop=10;fontFamily=Courier New;fontSize=13;')


